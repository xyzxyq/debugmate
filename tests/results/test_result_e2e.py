class _DecodableFixtureSapi:
    """Offline fake adapter that returns a real, tag-free MP3 fixture.

    The backend is deliberately the local fallback label.  The bytes are
    generated by fixed test-only FFmpeg arguments, then pass the production
    canonicalisation and ffprobe gates; no cloud TTS is invoked or claimed.
    """

    backend = "sapi"

    def __init__(self, payload: bytes) -> None:
        self._payload = payload

    def synthesize(self, _recap, request: TtsRequestIdentity, rate: RateProfile) -> AudioPayload:
        return AudioPayload(
            backend=self.backend,
            rate_profile=rate,
            request_identity=request,
            audio_bytes=self._payload,
            voice=None,
        )


def _request(recap) -> TtsRequestIdentity:
    return TtsRequestIdentity(
        case_id=recap.identity.case_id,
        source_run_id=recap.identity.source_run_id,
        diagnosis_sha256=recap.identity.diagnosis_sha256,
        generation_version=recap.identity.generation_version,
        recap_sha256=recap.sha256,
    )


def _tag_free_tone_mp3(target: Path) -> bytes:
    """Build a bounded, non-silent test MP3 through the pinned FFmpeg binary.

    Silence is deliberately too ZIP-compressible for the product's 100:1
    archive-ratio guard.  A deterministic tone provides real decodable media
    without weakening that guard or claiming a real voice synthesis run.
    """

    ffmpeg = trusted_media_tools().ffmpeg
    subprocess.run(
        [
            str(ffmpeg),
            "-v",
            "error",
            "-nostdin",
            "-y",
            "-f",
            "lavfi",
            "-i",
            "sine=frequency=440:sample_rate=16000",
            "-t",
            "45",
            "-map_metadata",
            "-1",
            "-metadata",
            "encoder=",
            "-id3v2_version",
            "0",
            "-write_xing",
            "0",
            "-ac",
            "1",
            "-codec:a",
            "libmp3lame",
            "-b:a",
            "32k",
            str(target),
        ],
        check=True,
        shell=False,
        timeout=30,
    )
    return target.read_bytes()


def _real_completed_bundle(completed_source_bundle, tmp_path: Path):
    """Compose one full bundle with an offline fake adapter and real media."""

    outcome, source_path = completed_source_bundle
    font = _font_copy(tmp_path)
    context = prepare_generation_context(
        project_root=tmp_path,
        project_font_candidates=(f"fonts/{font.name}",),
        windows_font_candidates=(),
    )
    source = load_verified_outcome(outcome, evidence_root=source_path.parents[1])
    presentation = build_presentation(source, context)
    report = render_report(presentation)
    citations = render_citations(presentation)
    recap = compose_recap(presentation)
    card = render_card(presentation, context, target=tmp_path / "card.png")
    # 45 seconds gives the MP3 frame quantiser margin while retaining the
    # product's inclusive 30--60 second media contract.
    raw_mp3 = _tag_free_tone_mp3(tmp_path / "fixture.mp3")
    audio = TtsFallbackChain(
        (_FailAdapter("dify"), _FailAdapter("edge_tts"), _DecodableFixtureSapi(raw_mp3))
    ).synthesize(
        recap,
        _request(recap),
        TrustedCandidateRoot.for_testing(tmp_path / "private"),
    )
    candidate = validate_result_candidates(
        source, presentation, report, citations, card, recap, audio
    )
    root = TrustedResultRoot.for_testing(tmp_path / "results")
    bundle = publish_result_bundle(root, candidate)
    return outcome, source_path, root, bundle


def _restore_service(
    *, outcome, source_path: Path, root: TrustedResultRoot, tmp_path: Path
) -> ResultApplicationService:
    store = DiagnosisOutcomeStore(tmp_path / "outcomes")
    store.write(outcome)
    return ResultApplicationService(
        workflow=None,
        evidence_root=source_path.parents[1],
        outcome_store=store,
        results_root=root,
        replay_root=Path(__file__).resolve().parents[2] / "fixtures" / "replay",
        composer=None,
    )


def test_completed_result_e2e(completed_source_bundle, tmp_path: Path) -> None:
    """Completed output is real-media, disk-verified and safe to restore/download."""

    outcome, source_path, root, bundle = _real_completed_bundle(
        completed_source_bundle, tmp_path
    )
    verified = verify_result_bundle(bundle.path)
    assert verified.manifest == bundle.manifest
    assert verified.manifest.status.value == "completed"
    assert verified.manifest.audio is not None
    assert verified.manifest.audio.backend == "sapi"
    probe = probe_mp3(bundle.path / "recap.mp3", timeout_seconds=15.0, max_bytes=8_000_000)
    assert probe.duration_ms == verified.manifest.audio.duration_ms
    service = _restore_service(
        outcome=outcome, source_path=source_path, root=root, tmp_path=tmp_path
    )
    state = service.restore_result(
        verified.manifest.identity.case_id, verified.manifest.result_id
    )
    assert state.status.value == "completed"
    assert state.result_id == verified.manifest.result_id
    archive = service.resolve_download(
        verified.manifest.identity.case_id, verified.manifest.result_id, "bundle"
    ).read_bytes()
    assert archive[:4] == b"PK\x03\x04"


def test_png_partial_result_e2e(candidates, tmp_path: Path) -> None:
    """A card layout failure preserves only the verified non-card modalities."""

    source, presentation, report, citations, _card, recap, audio = candidates
    root = TrustedResultRoot.for_testing(tmp_path / "results")
    candidate = validate_result_candidates(
        source,
        presentation,
        report,
        citations,
        CardRenderFailure("png_layout_failed"),
        recap,
        audio,
    )

    def compose(_source, *, mode, execution_backend, fixture_id, fixture_name):
        return publish_result_bundle(
            root,
            candidate,
            mode=mode,
            execution_backend=execution_backend,
            fixture_id=fixture_id,
            fixture_name=fixture_name,
        )

    service = _service(tmp_path, composer=compose)
    state = service.load_replay("module-not-found")
    assert state.status.value == "partial"
    assert state.failure is not None and state.failure.code == "png_layout_failed"
    assert state.availability.card is False and state.availability.audio is True
    assert state.identity is not None and state.result_id is not None
    verified = verify_result_bundle(
        tmp_path / "results" / state.identity.case_id / state.result_id
    )
    assert verified.manifest.status.value == "partial"
    assert not (verified.path / "card.png").exists()
    assert service.restore_result(state.identity.case_id, state.result_id) == state
    assert service.resolve_download(
        state.identity.case_id, state.result_id, "bundle"
    ).filename.endswith("partial.zip")


def test_tts_partial_result_e2e(candidates, tmp_path: Path) -> None:
    """All-TTS failure remains a truthful partial result with a transcript."""

    source, presentation, report, citations, card, recap, _audio = candidates
    unavailable = TtsFallbackChain(
        (_FailAdapter("dify"), _FailAdapter("edge_tts"), _FailAdapter("sapi"))
    ).synthesize(
        recap,
        _request(recap),
        # ``candidates`` owns an unconsumed successful-handoff lease under
        # ``private`` until its publisher runs, so the failure scenario needs
        # an independent private root instead of racing that lease.
        TrustedCandidateRoot.for_testing(tmp_path / "tts-partial-private"),
    )
    root = TrustedResultRoot.for_testing(tmp_path / "results")
    candidate = validate_result_candidates(
        source, presentation, report, citations, card, recap, unavailable
    )

    def compose(_source, *, mode, execution_backend, fixture_id, fixture_name):
        return publish_result_bundle(
            root,
            candidate,
            mode=mode,
            execution_backend=execution_backend,
            fixture_id=fixture_id,
            fixture_name=fixture_name,
        )

    service = _service(tmp_path, composer=compose)
    state = service.load_replay("module-not-found")
    assert state.status.value == "partial"
    assert state.failure is not None and state.failure.code == "tts_failed"
    assert state.availability.audio is False and state.availability.recap_text is True
    assert state.identity is not None and state.result_id is not None
    verified = verify_result_bundle(
        tmp_path / "results" / state.identity.case_id / state.result_id
    )
    assert not (verified.path / "recap.mp3").exists()
    assert service.restore_result(state.identity.case_id, state.result_id) == state
    assert service.resolve_download(
        state.identity.case_id, state.result_id, "recap_text"
    ).read_bytes()


def test_source_invalid_failed_e2e(candidates, tmp_path: Path) -> None:
    """A source failure publishes no result directory or download capability."""

    replay = tmp_path / "replay"
    shutil.copytree(Path(__file__).resolve().parents[2] / "fixtures" / "replay", replay)
    source_manifest = next(replay.glob("module-not-found/source/*/*/manifest.json"))
    source_manifest.write_text("{}", encoding="utf-8")
    service = _service(tmp_path, candidates)
    service._replay_root = replay
    state = service.load_replay("module-not-found")
    assert state.status.value == "failed"
    assert state.failure is not None and state.failure.code == "replay_bundle_invalid"
    assert state.identity is None and state.result_id is None
    results = tmp_path / "results"
    assert not list(results.rglob("result_*")) if results.exists() else True


def test_allowlisted_replay_result_e2e(candidates, tmp_path: Path) -> None:
    """Replay state, manifest and archive metadata share one allowlisted identity."""

    service = _service(tmp_path, candidates)
    state = service.load_replay("module-not-found")
    assert state.mode.value == "replay"
    assert state.fixture_id == "module-not-found"
    assert state.identity is not None and state.result_id is not None
    verified = verify_result_bundle(tmp_path / "results" / state.identity.case_id / state.result_id)
    assert verified.manifest.mode.value == "replay"
    assert verified.manifest.fixture_id == state.fixture_id
    assert verified.publication["status"] == "completed"
    assert service.restore_result(state.identity.case_id, state.result_id) == state
