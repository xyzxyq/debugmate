"""Phase 4 final source-to-result-to-restore acceptance evidence.

These tests deliberately exercise public service/publication boundaries and
re-open the final result directories.  They are not renderer return-value
tests: every successful assertion is based on ``verify_result_bundle`` bytes.
"""

