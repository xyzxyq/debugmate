"""Build the current, claim-safe Phase 09 evaluation ledger atomically."""

from __future__ import annotations

import hashlib
import json
import shutil
import subprocess
from datetime import UTC, datetime
from pathlib import Path

from debugmate.evaluation.collector import build_phase10_source_manifest, collect_phase9_cases
from debugmate.evaluation.contracts import (
    AcceptedV1ContractManifest,
    AcceptedV1Output,
    CaseRegistry,
    PromptComparison,
    PromptCriteriaRegistry,
    PromptEvidenceKind,
    PromptSourceEvidence,
)
from debugmate.evaluation.reports import (
    render_case_report,
    render_phase10_source,
    render_prompt_comparison,
    render_workflow_source,
)

ROOT = Path(__file__).resolve().parents[1]
TARGET = ROOT / "evidence" / "evaluation" / "phase9"
STAGING = ROOT / "evidence" / "evaluation" / ".phase9-staging"
GENERATED_BY = "scripts/run-phase9-evaluation.py"


def digest(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def file_digest(path: Path) -> str:
    return digest(path.read_bytes())


def generated_json(payload: dict[str, object]) -> bytes:
    payload = {
        "generated_by": GENERATED_BY,
        "manual_edits_permitted": False,
        **payload,
    }
    return (json.dumps(payload, ensure_ascii=False, sort_keys=True, indent=2) + "\n").encode()


def main() -> int:
    registry_path = ROOT / "evaluation" / "phase9" / "cases.json"
    criteria_path = ROOT / "evaluation" / "phase9" / "prompt-criteria.json"
    registry = CaseRegistry.model_validate_json(registry_path.read_bytes(), strict=True)
    criteria = PromptCriteriaRegistry.model_validate_json(criteria_path.read_bytes(), strict=True)
    accepted_manifest_path = (
        ROOT / "evidence" / "evaluation" / "phase9" / "accepted-v1-contract.json"
    )
    accepted_manifest = AcceptedV1ContractManifest.model_validate_json(
        accepted_manifest_path.read_bytes(), strict=True
    )
    accepted = AcceptedV1Output(
        conclusion=accepted_manifest.binding.conclusion,
        accepted_diagnosis_sha256=accepted_manifest.binding.accepted_diagnosis_sha256,
        accepted_result_sha256=accepted_manifest.binding.accepted_result_sha256,
        candidate_sha256=accepted_manifest.binding.candidate_sha256,
    )
    source_evidence = PromptSourceEvidence(
        kind=PromptEvidenceKind.ACCEPTED_V1_CONTRACT,
        reference={
            "path": {"path": accepted_manifest_path.relative_to(ROOT).as_posix()},
            "sha256": file_digest(accepted_manifest_path),
        },
    )
    prompt_rows = []
    for criterion in criteria.rows:
        prompt_rows.append(
            {
                "version": criterion.version,
                "prompt_file": criterion.prompt_file,
                "common_input": accepted_manifest.binding.common_input,
                "conclusion": accepted.conclusion,
                "accepted_diagnosis_sha256": accepted.accepted_diagnosis_sha256,
                "accepted_result_sha256": accepted.accepted_result_sha256,
                "candidate_sha256": accepted.candidate_sha256,
                "source_evidence": source_evidence,
                "provenance": "verified_contract" if criterion.version.value == "v1" else "blocked",
                "status": "accepted" if criterion.version.value == "v1" else "blocked",
            }
        )
    comparison = PromptComparison(
        comparison_version="phase9-prompt-comparison-1.0",
        common_input=accepted_manifest.binding.common_input,
        accepted_v1=accepted,
        rows=prompt_rows,
    )
    rows = collect_phase9_cases(registry, repository_root=ROOT)
    phase10 = build_phase10_source_manifest(rows)
    reports = {
        "case-results.json": render_case_report(rows),
        "prompt-comparison.json": render_prompt_comparison(comparison),
        "workflow-source.json": render_workflow_source(rows, comparison),
        "phase10-inputs.json": render_phase10_source(rows),
    }
    if STAGING.exists():
        shutil.rmtree(STAGING)
    STAGING.mkdir(parents=True)
    try:
        for seed_name in ("accepted-v1-contract.json", "run-v2.json"):
            seed_path = TARGET / seed_name
            if not seed_path.is_file():
                raise FileNotFoundError(f"Phase 09 prompt seed is missing: {seed_name}")
            shutil.copy2(seed_path, STAGING / seed_name)
        for name, rendered in reports.items():
            payload = json.loads(rendered.json_bytes)
            (STAGING / name).write_bytes(generated_json(payload))
        for name, rendered in (
            ("current-evaluation.md", reports["case-results.json"]),
            ("current-prompt-comparison.md", reports["prompt-comparison.json"]),
        ):
            marker = f"<!-- GENERATED BY {GENERATED_BY}; MANUAL EDITS PERMITTED: FALSE -->\n"
            (STAGING / name).write_bytes(marker.encode() + rendered.markdown_bytes)

        source_manifest = ROOT / "evidence" / "dify-live" / "phase8" / "manifest.json"
        source_summary = (
            ROOT / ".planning" / "phases" / "08-dify-unified-live-chain" / "08-07-SUMMARY.md"
        )
        source_commit = subprocess.run(
            ["git", "rev-parse", "HEAD"], cwd=ROOT, check=True, capture_output=True, text=True
        ).stdout.strip()
        artifacts = sorted(path.name for path in STAGING.iterdir())
        manifest_payload = {
            "manifest_version": "phase9-evaluation-1.0",
            "status": "accepted_with_explicit_blockers",
            "generated_by": GENERATED_BY,
            "manual_edits_permitted": False,
            "created_at_utc": datetime.now(UTC).strftime("%Y-%m-%dT%H:%M:%SZ"),
            "source_commit": source_commit,
            "phase8_summary_sha256": file_digest(source_summary),
            "phase8_manifest_sha256": file_digest(source_manifest),
            "case_registry_sha256": file_digest(registry_path),
            "prompt_criteria_sha256": file_digest(criteria_path),
            "knowledge_build_id": (
                "e8e065b4e33f3090687569c409e3695e304ba52b068cf0e08d1c93cb139c71ff"
            ),
            "case_count": len(rows),
            "phase10_eligible_count": len(phase10.cases),
            "artifacts": artifacts,
        }
        (STAGING / "manifest.json").write_bytes(generated_json(manifest_payload))
        checksum_names = sorted(path.name for path in STAGING.iterdir())
        checksum_lines = [f"{file_digest(STAGING / name)}  {name}" for name in checksum_names]
        (STAGING / "checksums.sha256").write_text(
            "# GENERATED BY scripts/run-phase9-evaluation.py; MANUAL EDITS PERMITTED: FALSE\n"
            + "\n".join(checksum_lines)
            + "\n",
            encoding="ascii",
        )
        if TARGET.exists():
            backup = TARGET.with_name("phase9-backup")
            if backup.exists():
                shutil.rmtree(backup)
            TARGET.rename(backup)
            try:
                STAGING.rename(TARGET)
            except Exception:
                backup.rename(TARGET)
                raise
            shutil.rmtree(backup)
        else:
            STAGING.rename(TARGET)
        docs_root = ROOT / "docs" / "course"
        docs_root.mkdir(parents=True, exist_ok=True)
        shutil.copy2(TARGET / "current-evaluation.md", docs_root / "current-evaluation.md")
        shutil.copy2(
            TARGET / "current-prompt-comparison.md", docs_root / "current-prompt-comparison.md"
        )
    except Exception:
        if STAGING.exists():
            shutil.rmtree(STAGING)
        raise
    print("phase9_evaluation_promoted")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
